# prompt_log.md::Raw GPT-4 output has been filled in.

SET_L: list[MR] = [
    MR(name="L_rot",        block="G",     set_label="L", fn=_placeholder_rot_fn),
    MR(name="L_perturb",    block="(out)", set_label="L", fn=_placeholder_perturb_fn),
    MR(name="L_prob_valid", block="(out)", set_label="L", fn=_placeholder_prob_valid_fn),
    MR(name="L_scale",      block="(out)", set_label="L", fn=_placeholder_scale_fn),
    MR(name="L_determ",     block="L*",    set_label="L", fn=_placeholder_determ_fn),
]


